    mutual: true,
    // 除外は他の一次ラベルの判定結果に委ねる（残余の定義）。**双方の判定を見る**。
    //
    // ⚠ **`雁木` は除外に入れない**（2026-08-05 に外した）。雁木は囲いであって戦法ではなく、
    // **相掛かりの将棋で雁木に囲うのは普通のこと**（`ショーダンオリジナル.kif` は
    // 13〜15手目に飛車先を交換してから 17▲6六歩 21▲6七銀 と組む、まさにその形）。
