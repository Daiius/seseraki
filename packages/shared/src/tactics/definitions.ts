/**
 * 内部ラベルごとの真偽の時系列。index = 手数（0 は使わない）。
 * **窓は掛けずに全手数分を持つ**（窓は参照する側＝一次/二次ラベルごとに決まるため）。
 */
export type Timeline = Map<string, boolean[]>;

/**
 * 一次 / 二次ラベルから内部ラベルを読むためのレンズ。
 *
 * - `limit` … このラベルの窓。参照する内部ラベルの除外集合の**和**から決まる
 * - `uses`  … 宣言された参照先。宣言外を読んだら落とす（窓の計算と実際の参照がずれるのを防ぐ）
 */
export class Lens {
  constructor(
    private readonly selfTl: Timeline,
    private readonly oppTl: Timeline,
    readonly limit: number,
    private readonly uses: Set<string>,
  ) {}

  private arr(tl: Timeline, name: string): boolean[] {
    if (!this.uses.has(name)) throw new Error(`uses に宣言されていない内部ラベルを参照した: ${name}`);
    const a = tl.get(name);
    if (!a) throw new Error(`未定義の内部ラベル: ${name}`);
    return a;
  }

  /** その内部ラベルが最初に真になった手数 */
  first(name: string): number | null {
    const a = this.arr(this.selfTl, name);
    for (let i = 1; i <= Math.min(this.limit, a.length - 1); i++) if (a[i]) return i;
    return null;
  }

  /** 相手側で最初に真になった手数 */
  oppFirst(name: string): number | null {
    const a = this.arr(this.oppTl, name);
    for (let i = 1; i <= Math.min(this.limit, a.length - 1); i++) if (a[i]) return i;
    return null;
  }

  /** 複数の内部ラベルが**同時に**真になる最小の手数 */
  co(...names: string[]): number | null {
    const arrays = names.map((n) => this.arr(this.selfTl, n));
    const len = Math.min(this.limit, ...arrays.map((a) => a.length - 1));
    for (let i = 1; i <= len; i++) if (arrays.every((a) => a[i])) return i;
    return null;
  }

  /**
   * 指定の順序で成立したか（間に他の事象が挟まってよい）。成立した手数を返す。
   * 「一度成立したら降りない」ではなく**真になった瞬間**を辿る。
   */
  seq(...names: string[]): number | null {
    let from = 1;
    for (const name of names) {
      const a = this.arr(this.selfTl, name);
      let hit: number | null = null;
      for (let i = from; i <= Math.min(this.limit, a.length - 1); i++) {
        if (a[i]) {
          hit = i;
          break;
        }
      }
      if (hit === null) return null;
      from = hit;
    }
    return from;
  }
}

